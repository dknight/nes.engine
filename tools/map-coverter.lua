#!/usr/bin/env lua

-- Converts a human-readable map into a TILE_* map.

local mapfile_path = arg[1]

local function report_error(err)
	return string.format("error: %s", err)
end

local function split_chars(s)
	local chars = {}
	for i = 1, #s do
		chars[i] = s:sub(i, i)
	end
	return chars
end

local function parse_map_file()
	local output = {}
	local replacements = {}
	local is_in_map = false
	local line_number = 0

	for line in io.lines(mapfile_path) do
		line_number = line_number + 1

		if not is_in_map then
			local ch, tile = line:match("^%s*(.)%s*=%s*([%w_]+)%s*$")

			if ch and tile then
				replacements[ch] = tile
			end

			-- Start reading the map after the separator.
			if line:match("^%-%-+%s*$") then
				is_in_map = true
			end

			goto continue
		end

		if line == "" then
			goto continue
		end

		local chars = split_chars(line)
		local tiles = {}

		for _, ch in ipairs(chars) do
			local tile = replacements[ch]

			if not tile then
				return nil, string.format(
					"unknown character '%s' at line %d",
					ch,
					line_number
				)
			end

			table.insert(tiles, tile)
		end

		table.insert(output, ".byte " .. table.concat(tiles, ","))

		::continue::
	end

	if not is_in_map then
		return nil, "map separator not found"
	end

	if #output == 0 then
		return nil, "map is empty"
	end

	return output
end

local function main()
	if not mapfile_path then
		print(report_error("usage: lua map-converter.lua <mapfile>"))
		os.exit(1)
	end

	local fd = io.open(mapfile_path, "r")
	if not fd then
		print(report_error("cannot open " .. mapfile_path))
		os.exit(1)
	end
	fd:close()

	local output, err = parse_map_file()

	if not output then
		print(report_error(err))
		os.exit(1)
	end

	io.write("; Generated by " .. arg[0] .. "\n")
	io.write(table.concat(output, "\n"))
end

main()
